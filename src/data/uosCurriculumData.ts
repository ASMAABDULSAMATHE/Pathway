// Helper to determine discipline from major or college name
export function getDisciplineFromMajor(majorStr: string, collegeStr?: string): DisciplineType {
  const combined = `${majorStr} ${collegeStr || ''}`.toLowerCase();

  if (
    combined.includes('health') ||
    combined.includes('nurs') ||
    combined.includes('medic') ||
    combined.includes('pharm') ||
    combined.includes('clinic') ||
    combined.includes('physio') ||
    combined.includes('nutrition') ||
    combined.includes('dietet') ||
    combined.includes('laborat') ||
    combined.includes('dental') ||
    combined.includes('patient')
  ) {
    return 'health';
  }

  if (
    combined.includes('comput') ||
    combined.includes('software') ||
    combined.includes('cyber') ||
    combined.includes(' artificial ') ||
    combined.includes(' ai ') ||
    combined.includes('ai ') ||
    combined.includes('information tech') ||
    combined.includes('data sci')
  ) {
    return 'computing';
  }

  if (
    combined.includes('engin') ||
    combined.includes('electr') ||
    combined.includes('mechan') ||
    combined.includes('civil') ||
    combined.includes('industr') ||
    combined.includes('mechatron') ||
    combined.includes('renewab')
  ) {
    return 'engineering';
  }

  if (
    combined.includes('law') ||
    combined.includes('public relat') ||
    combined.includes('media') ||
    combined.includes('commun') ||
    combined.includes('psychol') ||
    combined.includes('internat')
  ) {
    return 'humanities';
  }

  // Default to business if business/bis or general
  return 'business';
}
