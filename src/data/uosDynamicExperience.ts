// Dispatcher function that returns the full experience tailored to any major/college
export function getDisciplineExperience(majorStr: string, collegeStr?: string): DisciplineExperience {
  const discipline = getDisciplineFromMajor(majorStr, collegeStr);

  switch (discipline) {
    case 'health':
      return HEALTH_EXPERIENCE;
    case 'computing':
      return COMPUTING_EXPERIENCE;
    case 'engineering':
      return ENGINEERING_EXPERIENCE;
    case 'humanities':
      return HUMANITIES_EXPERIENCE;
    case 'business':
    default:
      return BUSINESS_EXPERIENCE;
  }
}